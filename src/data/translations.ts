export type TranslationShape = typeof translations['en'];

export function tKey(
  language: Language,
  path: string,
  params?: Record<string, string | number>
): string {
  const resolve = (obj: any, p: string): string | undefined => {
    const parts = p.split('.');
    let cur = obj;
    for (const part of parts) {
      if (cur && typeof cur === 'object' && part in cur) {
        cur = cur[part];
      } else {
        return undefined;
      }
    }
    return typeof cur === 'string' ? cur : undefined;
  };

  let val = resolve(translations[language], path);
  if (val === undefined) {
    if (!warnedKeys.has(`${language}:${path}`)) {
      warnedKeys.add(`${language}:${path}`);
      if (language !== 'en') {
        console.warn(`[i18n] Missing "${language}" translation key: "${path}"`);
      }
    }
    val = resolve(translations.en, path) ?? path;
  }

  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      val = val!.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    });
  }
  return val;
}

export function formatLocalizedNumber(value: number, language: Language): string {
  if (!Number.isFinite(value)) return '0';
  try {
    return new Intl.NumberFormat(language === 'bn' ? 'bn-BD' : 'en-US').format(value);
  } catch {
    return String(value);
  }
}

export function formatLocalizedDate(raw: Date | string | number, language: Language): string {
  if (!raw) return language === 'bn' ? 'এইমাত্র' : 'Just now';
  const dateObj = raw instanceof Date ? raw : new Date(raw);
  if (Number.isNaN(dateObj.getTime())) return String(raw);
  try {
    return dateObj.toLocaleDateString(language === 'bn' ? 'bn-BD' : 'en-US', {
      month: 'short',
      day: 'numeric',
      year: 'numeric',
    });
  } catch {
    return String(raw);
  }
}
